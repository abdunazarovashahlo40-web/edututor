export function buildOpenApi() {
  const paths: Record<string, Record<string, unknown>> = {};
  for (const [method, path, tag, summary, auth] of routes) {
    const params = [...path.matchAll(/\{(\w+)\}/g)].map((m) => ({ name: m[1], in: 'path', required: true, schema: { type: 'string' } }));
    paths[path] ??= {};
    paths[path][method] = {
      tags: [tag],
      summary,
      description: auth ? `Ruxsat: **${auth}**` : 'Ochiq',
      parameters: params,
      ...(auth ? { security: [{ cookieAuth: [] }] } : {}),
      responses: {
        200: { description: '{ ok: true, data, meta? }' },
        400: { description: 'VALIDATION_ERROR' },
        401: { description: 'UNAUTHORIZED' },
        403: { description: 'FORBIDDEN / CSRF_INVALID' },
        409: { description: 'CONFLICT (masalan SLOT_TAKEN)' },
        423: { description: 'APP_LOCKED — ilova qulflangan' },
      },
    };
  }
  return {
    openapi: '3.0.3',
    info: {
      title: 'EduTutor API',
      version: '1.0.0',
      description:
        'Onlayn repetitorlik platformasi REST API. Barcha o\'zgartiruvchi so\'rovlar `X-CSRF-Token` sarlavhasini (et_csrf cookie qiymati) talab qiladi.',
    },
    servers: [{ url: '/api/v1' }],
    components: { securitySchemes: { cookieAuth: { type: 'apiKey', in: 'cookie', name: 'et_access' } } },
    paths,
  };
}
